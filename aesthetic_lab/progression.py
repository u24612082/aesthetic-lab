"""Deterministic technique gate inspired by ANPC86/claude-smart-gym-coach.

No sensor scores are generated by this module. No programme or load is changed.
"""
import json
from collections import defaultdict

from .ingest import MOVEMENTS, normalize

COMPOUNDS = {
    "incline smith press", "hip thrusts", "bulgarian split squats", "neutral grip pulldown",
    "single arm pulldown", "machine neutral row", "glute biased leg press", "quad focused leg press",
    "incline dumbbell press", "incline bench press", "incline barbell bench press",
    "bench press", "flat dumbbell press", "overhead press", "lat pulldown", "pull up",
    "chest supported row", "seated cable row", "barbell row", "squat", "barbell squat",
    "hack squat", "leg press", "romanian deadlift", "hip thrust",
}


def technique_gates(sets):
    groups = defaultdict(list)
    for s in sets:
        if not s["warmup"]:
            key = (normalize(s["exercise"]), s.get("equipment_id"), s.get("resistance_mode", "unknown"), s["side"])
            groups[key].append(s)
    result = []
    for (movement, equipment, mode, side), records in groups.items():
        # Read the latest session, including missing scores. Never carry an older pass forward.
        latest = max(records, key=lambda r: (r["started_at"], r["workout_id"]))
        current = [s for s in records if s["workout_id"] == latest["workout_id"]]
        threshold = 4 if movement in COMPOUNDS else 3
        kind = "compound" if movement in COMPOUNDS else "isolation" if movement in MOVEMENTS else "unknown"
        reasons, missing, failed = [], False, False
        scores = [json.loads(s["technique_json"]) if s.get("technique_json") else {} for s in current]
        if kind == "unknown":
            missing = True
            reasons.append("Movement classification is unverified; add a reviewed exercise mapping.")
        if not equipment or mode == "unknown" or side == "unknown":
            missing = True
            reasons.append("Equipment, resistance mode and side must be explicit before load review.")
        if any(not s.get("evidence_source") or s.get("amplitudeStableScore") is None or s.get("forceControlScore") is None for s in scores):
            missing = True
            reasons.append("Missing measured amplitude / force-control scores on one or more working sets.")
        for label, key in (("Amplitude", "amplitudeStableScore"), ("Force control", "forceControlScore")):
            values = [s[key] for s in scores if s.get(key) is not None]
            if values and min(values) < threshold:
                failed = True
                reasons.append(f"{label} minimum {min(values)}/5; {kind} threshold is {threshold}/5 on every working set.")
        # A unilateral zero is a device artifact, never evidence of bilateral imbalance.
        balance = [s["bilateralBalanceScore"] for s in scores if s.get("bilateralBalanceScore") is not None]
        if side == "bilateral" and balance and min(balance) < 3:
            failed = True
            reasons.append("Bilateral balance below 3/5: hold load and review the measured imbalance.")
        status = "hold" if failed else "insufficient_data" if missing else "passed"
        if status == "passed":
            reasons.append(f"All {len(current)} working sets meet amplitude and force-control ≥{threshold}/5.")
            reasons.append("Technique prerequisite passed; rep targets, effort and progression context still require review.")
        result.append({"exercise": latest["exercise"], "equipment_id": equipment, "resistance_mode": mode, "side": side,
                       "session_date": latest["local_date"], "status": status, "movement_kind": kind,
                       "threshold": threshold, "working_sets": len(current), "reasons": reasons,
                       "eligible_for_load_review": status == "passed"})
    return sorted(result, key=lambda r: (r["status"] == "passed", r["exercise"]))
