#!/usr/bin/env python3
"""Reproducible, local public-domain photos; no runtime CDN or API dependency."""
import hashlib
import json
import re
import sys
from concurrent.futures import ThreadPoolExecutor,as_completed
from pathlib import Path,PurePosixPath
from urllib.parse import quote
import httpx
from build_exercise_diagrams import build as build_diagrams

ROOT=Path(__file__).resolve().parent.parent
REVISION='f00c92c7dcf1216a928a52c3706c7ce8e2f71ed5'
REPO='https://github.com/yuhonas/free-exercise-db'
RAW=f'https://raw.githubusercontent.com/yuhonas/free-exercise-db/{REVISION}'
OUT=ROOT/'aesthetic_lab/exercise_media'


def normal(name):return re.sub(r'[^a-z0-9]','',name.lower()).removesuffix('s')


def main():
    OUT.mkdir(exist_ok=True);(OUT/'photos').mkdir(exist_ok=True)
    with httpx.Client(timeout=35,follow_redirects=True,headers={'User-Agent':'AestheticLab/0.1 public-domain exercise images'},limits=httpx.Limits(max_connections=6)) as client:
        source=ROOT/'aesthetic_lab/data/exercise_photo_source.json'
        if not source.exists():
            r=client.get(RAW+'/dist/exercises.json');r.raise_for_status();source.write_bytes(r.content)
        rows=json.loads(source.read_text(encoding='utf-8'));index={r['id']:r for r in rows};by_name={normal(r['name']):r['id'] for r in rows}
        license_path=OUT/'LICENSE.free-exercise-db.txt'
        if not license_path.exists():
            r=client.get(RAW+'/LICENSE.md');r.raise_for_status();license_path.write_bytes(r.content)
        rules=json.loads((ROOT/'aesthetic_lab/data/exercise_media_aliases.json').read_text(encoding='utf-8'))
        legacy=json.loads((ROOT/'opengym/frontend/src/lib/exercises-data.js').read_text(encoding='utf-8').split('=',1)[1].rstrip(';\n'))
        ids={e['id']:{'asset':by_name[normal(e['n'])]} for e in legacy if normal(e['n']) in by_name}
        ids.update(rules['legacy_ids']);names={normal(name):rule for name,rule in rules['names'].items()}
        for rule in ids.values():
            if rule['asset'] in index:names.setdefault(normal(index[rule['asset']]['name']),{'asset':rule['asset']})
        wanted={asset for rule in [*ids.values(),*names.values()] for asset in [rule['asset'],*rule.get('variants',[])]}
        catalog=build_diagrams();downloads=[]
        for key in sorted(wanted):
            if key.startswith('diagram:'):
                if key not in catalog:raise ValueError('Missing original illustration: '+key)
                continue
            row=index[key];frames=[]
            for i,image in enumerate(row['images'][:2]):
                parts=PurePosixPath(image).parts
                if len(parts)!=2 or parts[0]!=key or '..' in parts:raise ValueError('Unexpected image path')
                target=OUT/'photos'/f'{key}-{i}.jpg';frames.append('/exercise-media/photos/'+quote(target.name))
                downloads.append((RAW+'/exercises/'+quote(image,safe='/'),target))
            catalog[key]={'name':row['name'],'kind':'photo','frames':frames,'labels':['Start','Finish'][:len(frames)],'source':'Free Exercise DB · public domain','source_url':REPO+'/tree/'+REVISION+'/exercises/'+quote(key)}
        def download(item):
            url,path=item
            if path.exists() and path.read_bytes().startswith(b'\xff\xd8\xff'):return
            for attempt in range(3):
                try:
                    r=client.get(url);r.raise_for_status()
                    if len(r.content)>2_000_000 or not r.content.startswith(b'\xff\xd8\xff'):raise ValueError('Unexpected image bytes: '+path.name)
                    path.write_bytes(r.content);return
                except httpx.HTTPError:
                    if attempt==2:raise
        with ThreadPoolExecutor(max_workers=6) as pool:
            futures=[pool.submit(download,item) for item in downloads]
            for i,f in enumerate(as_completed(futures),1):
                f.result()
                if i%40==0 or i==len(futures):print(f'Exercise images: {i}/{len(futures)}',flush=True)
        data={'revision':REVISION,'source':REPO,'catalog':catalog,'byName':names,'byId':ids}
        (ROOT/'aesthetic_lab/static/exercise-media-data.js').write_text('// Generated by scripts/fetch_exercise_media.py; see bundled source licence.\nexport const EXERCISE_MEDIA='+json.dumps(data,ensure_ascii=False,separators=(',',':'))+'\n')
        files=sorted(p for p in OUT.rglob('*') if p.suffix in ('.jpg','.svg'))
        manifest={'version':'exercise-media-'+REVISION[:12]+'-'+hashlib.sha256(''.join(hashlib.sha256(p.read_bytes()).hexdigest() for p in files).encode()).hexdigest()[:12],'source':REPO,'revision':REVISION,
                  'files':[{'url':'/exercise-media/'+quote(str(p.relative_to(OUT)),safe='/'),'sha256':hashlib.sha256(p.read_bytes()).hexdigest(),'bytes':p.stat().st_size} for p in files]}
        (OUT/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n',encoding='utf-8')
        print(f'Bundled {len(files)} images/diagrams ({sum(p.stat().st_size for p in files)/1_000_000:.1f} MB); {len(ids)} catalogue entries plus named routine matches.',flush=True)


if __name__=='__main__':main()
